from enum import Enum
from typing import Optional, Dict, Any, List
from datetime import datetime


class ComplaintCategory(str, Enum):
    ELECTRICITY_POWER = "Electricity & Power Outage"
    GAS_SUPPLY = "Gas Supply & Loadshedding"
    WASTE_SANITATION = "Waste & Sanitation"
    WATER_SUPPLY = "Water Supply & Leakage"
    DRAINAGE_SEWAGE = "Drainage & Sewerage"
    ROADS_INFRASTRUCTURE = "Roads & Infrastructure"
    PUBLIC_SAFETY = "Public Safety & Parks"
    OTHER = "Other Local Issues"


class PriorityLevel(str, Enum):
    LOW = "Low"
    MEDIUM = "Medium"
    HIGH = "High"
    CRITICAL = "Critical"


class ComplaintStatus(str, Enum):
    OPEN = "Open"
    ASSIGNED = "Assigned"
    IN_PROGRESS = "In Progress"
    RESOLVED = "Resolved"
    REJECTED = "Rejected"


class Citizen:
    """Represents a citizen entity submitting and tracking complaints."""
    def __init__(
        self,
        name: str,
        phone: str,
        email: str,
        ward: str = "Karachi - Gulshan-e-Iqbal"
    ):
        self._name = name.strip()
        self._phone = phone.strip()
        self._email = email.strip()
        self._ward = ward.strip()

    @property
    def name(self) -> str:
        return self._name

    @property
    def phone(self) -> str:
        return self._phone

    @property
    def email(self) -> str:
        return self._email

    @property
    def ward(self) -> str:
        return self._ward

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self._name,
            "phone": self._phone,
            "email": self._email,
            "ward": self._ward
        }


class Department:
    """Represents a responsible municipal service department (Pakistani Context)."""
    DEPARTMENT_MAPPING = {
        ComplaintCategory.ELECTRICITY_POWER: "Power Distribution Company (K-Electric / LESCO / IESCO)",
        ComplaintCategory.GAS_SUPPLY: "Sui Gas Authority (SSGC / SNGPL)",
        ComplaintCategory.WASTE_SANITATION: "Solid Waste Management Board (SSWMB / LWMC)",
        ComplaintCategory.WATER_SUPPLY: "Water & Sanitation Agency (WASA / KWSB)",
        ComplaintCategory.DRAINAGE_SEWAGE: "Drainage & Sewerage Division",
        ComplaintCategory.ROADS_INFRASTRUCTURE: "Metropolitan Development Authority (CDA / KDA / PWD)",
        ComplaintCategory.PUBLIC_SAFETY: "Parks & Civic Amenities Directorate",
        ComplaintCategory.OTHER: "General Civic Redressal Cell"
    }

    def __init__(self, name: str, contact_email: Optional[str] = None):
        self.name = name
        self.contact_email = contact_email or f"{name.lower().replace(' ', '.')}@civic.gov.pk"
        self.active_tickets_count = 0

    @classmethod
    def get_recommended_department(cls, category: str) -> str:
        for cat_enum, dept_name in cls.DEPARTMENT_MAPPING.items():
            if cat_enum.value.lower() == category.lower() or cat_enum.name.lower() == category.lower():
                return dept_name
        # Fallback keyword matching
        c_lower = category.lower()
        if "electr" in c_lower or "power" in c_lower or "bijli" in c_lower:
            return cls.DEPARTMENT_MAPPING[ComplaintCategory.ELECTRICITY_POWER]
        if "gas" in c_lower or "sui" in c_lower:
            return cls.DEPARTMENT_MAPPING[ComplaintCategory.GAS_SUPPLY]
        if "waste" in c_lower or "sanit" in c_lower or "kachra" in c_lower or "sweep" in c_lower:
            return cls.DEPARTMENT_MAPPING[ComplaintCategory.WASTE_SANITATION]
        if "water" in c_lower or "paani" in c_lower:
            return cls.DEPARTMENT_MAPPING[ComplaintCategory.WATER_SUPPLY]
        if "drain" in c_lower or "sewer" in c_lower or "gutter" in c_lower:
            return cls.DEPARTMENT_MAPPING[ComplaintCategory.DRAINAGE_SEWAGE]
        if "road" in c_lower or "pothole" in c_lower or "sadak" in c_lower:
            return cls.DEPARTMENT_MAPPING[ComplaintCategory.ROADS_INFRASTRUCTURE]
        if "safe" in c_lower or "park" in c_lower or "dog" in c_lower:
            return cls.DEPARTMENT_MAPPING[ComplaintCategory.PUBLIC_SAFETY]
        return "General Civic Redressal Cell"


class AIAnalysisResult:
    """Encapsulates the multi-output predictions generated by the AI Engine."""
    def __init__(
        self,
        predicted_category: str,
        confidence_score: float,
        predicted_priority: str,
        priority_score: float,
        actionable_summary: str,
        hazard_level: str,
        recommended_department: str,
        duplicate_detected: bool = False,
        duplicate_of_id: Optional[str] = None,
        duplicate_similarity: float = 0.0,
        vision_tags: Optional[List[str]] = None
    ):
        self.predicted_category = predicted_category
        self.confidence_score = round(confidence_score, 3)
        self.predicted_priority = predicted_priority
        self.priority_score = round(priority_score, 1)
        self.actionable_summary = actionable_summary
        self.hazard_level = hazard_level
        self.recommended_department = recommended_department
        self.duplicate_detected = duplicate_detected
        self.duplicate_of_id = duplicate_of_id
        self.duplicate_similarity = round(duplicate_similarity, 3)
        self.vision_tags = vision_tags or []

    def to_dict(self) -> Dict[str, Any]:
        return {
            "predicted_category": self.predicted_category,
            "confidence_score": self.confidence_score,
            "predicted_priority": self.predicted_priority,
            "priority_score": self.priority_score,
            "actionable_summary": self.actionable_summary,
            "hazard_level": self.hazard_level,
            "recommended_department": self.recommended_department,
            "duplicate_detected": self.duplicate_detected,
            "duplicate_of_id": self.duplicate_of_id,
            "duplicate_similarity": self.duplicate_similarity,
            "vision_tags": self.vision_tags
        }


class Complaint:
    """Core domain model representing a civic Complain with lifecycle and AI attributes."""
    def __init__(
        self,
        complaint_id: str,
        citizen: Citizen,
        description: str,
        location: str,
        category: str,
        priority: str,
        priority_score: float = 50.0,
        status: str = ComplaintStatus.OPEN.value,
        assigned_department: Optional[str] = None,
        ai_summary: Optional[str] = None,
        hazard_level: str = "Medium",
        image_url: Optional[str] = None,
        created_at: Optional[str] = None,
        resolved_at: Optional[str] = None,
        resolution_hours: Optional[float] = None
    ):
        self._id = complaint_id
        self._citizen = citizen
        self._description = description.strip()
        self._location = location.strip()
        self._category = category
        self._priority = priority
        self._priority_score = priority_score
        self._status = status
        self._assigned_department = assigned_department or Department.get_recommended_department(category)
        self._ai_summary = ai_summary or description[:120]
        self._hazard_level = hazard_level
        self._image_url = image_url
        self._created_at = created_at or datetime.now().isoformat()
        self._resolved_at = resolved_at
        self._resolution_hours = resolution_hours

    # Encapsulated Properties
    @property
    def id(self) -> str:
        return self._id

    @property
    def citizen(self) -> Citizen:
        return self._citizen

    @property
    def description(self) -> str:
        return self._description

    @property
    def location(self) -> str:
        return self._location

    @property
    def category(self) -> str:
        return self._category

    @property
    def priority(self) -> str:
        return self._priority

    @property
    def priority_score(self) -> float:
        return self._priority_score

    @property
    def status(self) -> str:
        return self._status

    @property
    def assigned_department(self) -> str:
        return self._assigned_department

    @property
    def ai_summary(self) -> str:
        return self._ai_summary

    @property
    def hazard_level(self) -> str:
        return self._hazard_level

    @property
    def image_url(self) -> Optional[str]:
        return self._image_url

    @property
    def created_at(self) -> str:
        return self._created_at

    @property
    def resolved_at(self) -> Optional[str]:
        return self._resolved_at

    @property
    def resolution_hours(self) -> Optional[float]:
        return self._resolution_hours

    # Lifecycle Methods (Domain Logic)
    def update_status(self, new_status: str) -> None:
        valid_statuses = [s.value for s in ComplaintStatus]
        if new_status not in valid_statuses:
            raise ValueError(f"Invalid status: {new_status}. Allowed: {valid_statuses}")
        self._status = new_status
        if new_status == ComplaintStatus.RESOLVED.value and not self._resolved_at:
            now = datetime.now()
            self._resolved_at = now.isoformat()
            try:
                c_time = datetime.fromisoformat(self._created_at)
                diff = now - c_time
                self._resolution_hours = round(diff.total_seconds() / 3600.0, 2)
            except Exception:
                self._resolution_hours = 24.0

    def assign_department(self, new_department: str) -> None:
        self._assigned_department = new_department.strip()
        if self._status == ComplaintStatus.OPEN.value:
            self._status = ComplaintStatus.ASSIGNED.value

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self._id,
            "citizen_name": self._citizen.name,
            "citizen_phone": self._citizen.phone,
            "citizen_email": self._citizen.email,
            "ward": self._citizen.ward,
            "location": self._location,
            "description": self._description,
            "category": self._category,
            "priority": self._priority,
            "priority_score": self._priority_score,
            "status": self._status,
            "assigned_department": self._assigned_department,
            "ai_summary": self._ai_summary,
            "hazard_level": self._hazard_level,
            "image_url": self._image_url,
            "created_at": self._created_at,
            "resolved_at": self._resolved_at,
            "resolution_hours": self._resolution_hours
        }
